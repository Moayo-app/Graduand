/**
 * 푸터 저작권 줄 — ⭐ **자구의 정본은 회사의 저작권 결정 기록이고 여기는 가리킨다.** 관행을
 * 걷은 근거(「All rights reserved」는 베른 체제에서 아무 일도 하지 않는다)와 연도를 남긴
 * 근거(형식 요건의 한 칸 · innocent-infringement 완화 항변 차단)를 여기 옮겨 적으면
 * 정본이 둘이 되고, 둘은 갈라진다.
 *
 * ⭐⭐ **끝 연도는 적지 않고 뽑는다.** 리터럴로 박으면 **발행본과 가드가 같이 낡아서** 해가
 * 바뀌어도 아무것도 빨개지지 않는다 — 가드가 낡음을 잡은 것이 아니라 **고정한다**(형제
 * 저장소의 실측에서 같은 병의 자리 여덟 중 **둘이 가드**였다).
 *
 * ⚠️ **이 함수가 낡음을 없애지 않는다 — 소스에서 배포로 옮긴다.** 정적 발행본의 끝 연도는
 * **빌드 시점**에 박히므로 다음 해에 배포가 한 번도 없으면 발행 표면은 지난 연도를 싣는다.
 * 그 남은 낡음은 **소스 가드로는 원리상 볼 수 없고**, 발행 표면을 밖에서 읽는 회사 저장소의
 * 워크플로가 문다. ⛔ 여기에 두 번째 사본을 만들지 않는다.
 *
 * ⚠️ **UTC 로 센다** — 빌드가 도는 자리가 둘(CI 러너 UTC · 로컬 KST)이라 지역을 고르지
 * 않으면 같은 코드가 자리마다 다른 연도를 낸다.
 * ⚠️ 구분자는 **en dash** 이고 순서는 **기호 → 연도 → 권리자**다.
 */
export function copyrightLine(
  now: Date = new Date(),
  firstPublished: number | null = FIRST_PUBLISHED,
): string {
  const current = now.getUTCFullYear();
  // 시작과 끝이 같으면(또는 기록이 아직 없으면) **접는다** — 범위로 두 번 적지 않는다.
  const years =
    firstPublished === null || firstPublished >= current
      ? `${current}`
      : `${firstPublished}–${current}`;
  return `© ${years} ${PUBLISHER.copyrightHolder}`;
}
